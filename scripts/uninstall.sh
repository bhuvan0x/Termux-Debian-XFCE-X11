#!/data/data/com.termux/files/usr/bin/bash
set -Eeuo pipefail

# Removes this repository's Debian workstation integration.
# Debian removal is destructive: all files inside the Debian PRoot distro are deleted.

SCRIPT_DIR="$(cd -- "$(dirname -- "${BASH_SOURCE[0]}")" && pwd)"
REPO_DIR="$(cd -- "$SCRIPT_DIR/.." && pwd)"
REMOVE_REPO=0
ASSUME_YES=0

usage() {
  cat <<'USAGE'
PrimeBook / Termux Debian X11 uninstaller

Usage:
  bash scripts/uninstall.sh
  bash scripts/uninstall.sh --remove-repo
  bash scripts/uninstall.sh --yes
  bash scripts/uninstall.sh --yes --remove-repo

Options:
  --remove-repo  Also delete this cloned repository after uninstalling.
  --yes          Skip the confirmation prompt (still prints the destructive scope).
  -h, --help     Show this help.

This removes the Debian PRoot distribution and the Termux commands/Widget
shortcuts generated by this project. It does not uninstall Termux, Android
add-on apps, or shared Termux packages.
USAGE
}

for arg in "$@"; do
  case "$arg" in
    --remove-repo) REMOVE_REPO=1 ;;
    --yes) ASSUME_YES=1 ;;
    -h|--help) usage; exit 0 ;;
    *) echo "Unknown option: $arg" >&2; usage >&2; exit 2 ;;
  esac
done

if [ -z "${PREFIX:-}" ] || [ ! -d "$PREFIX" ]; then
  echo "ERROR: Run this uninstaller inside Termux." >&2
  exit 1
fi

if ! command -v proot-distro >/dev/null 2>&1; then
  echo "ERROR: proot-distro is not installed; cannot verify/remove the Debian distro." >&2
  exit 1
fi

cat <<'WARNING'
DESTRUCTIVE OPERATION

The Debian PRoot distribution named 'debian' will be removed completely.
This permanently deletes its installed applications, Linux user accounts,
home directories, settings, and any personal files stored inside Debian.

The uninstaller also removes this project's Termux start/stop wrappers and
its known Termux:Widget shortcuts/tasks.

It does NOT remove:
  - Termux or Android add-on apps (Termux:X11, API, Widget)
  - Shared Termux packages such as Git, PulseAudio, proot-distro or X11
  - Files in Android shared storage / Downloads
  - This Git repository, unless --remove-repo is supplied
WARNING

if [ "$ASSUME_YES" -ne 1 ]; then
  printf '\nType REMOVE-DEBIAN to continue: '
  IFS= read -r confirmation
  if [ "$confirmation" != "REMOVE-DEBIAN" ]; then
    echo "Cancelled. Nothing was removed."
    exit 0
  fi
fi

echo
echo "== Stopping PrimeBook services =="
if [ -f "$REPO_DIR/scripts/stop-all.sh" ]; then
  bash "$REPO_DIR/scripts/stop-all.sh" || echo "WARNING: one or more stop actions returned an error; continuing."
fi

echo
echo "== Removing the Debian PRoot distribution =="
if proot-distro list 2>/dev/null | grep -qE '^  debian([[:space:]]|$)'; then
  proot-distro remove debian
else
  echo "Debian distribution is not listed as installed; skipping."
fi

echo
echo "== Removing project-generated Termux commands =="
for command_name in start-all stop-all uninstall-primebook; do
  command_path="$PREFIX/bin/$command_name"
  if [ -f "$command_path" ] && grep -Fq "$REPO_DIR" "$command_path"; then
    rm -f -- "$command_path"
    echo "Removed $command_path"
  else
    echo "Kept $command_path (not owned by this repository or not present)."
  fi
done

echo
echo "== Removing project-generated Termux:Widget shortcuts =="
SHORTCUTS_DIR="$HOME/.shortcuts"
TASKS_DIR="$SHORTCUTS_DIR/tasks"
for name in "Start All" "Stop All"; do
  [ ! -f "$SHORTCUTS_DIR/$name" ] || rm -f -- "$SHORTCUTS_DIR/$name"
done
for name in \
  "Update Debian packages" \
  "Harden Debian" \
  "Security audit" \
  "Termux security check" \
  "Install ClamAV" \
  "Update ClamAV signatures" \
  "Scan Debian Downloads" \
  "Refresh Debian desktop" \
  "Check USB devices" \
  "Install printer support"; do
  [ ! -f "$TASKS_DIR/$name" ] || rm -f -- "$TASKS_DIR/$name"
done

# Remove only directories if they are empty; never delete unrelated shortcuts.
rmdir "$TASKS_DIR" 2>/dev/null || true
rmdir "$SHORTCUTS_DIR" 2>/dev/null || true
hash -r 2>/dev/null || true

if [ "$REMOVE_REPO" -eq 1 ]; then
  case "$REPO_DIR/" in
    "$HOME/"*) ;;
    *)
      echo "ERROR: Refusing to delete a repository outside Termux HOME: $REPO_DIR" >&2
      exit 3
      ;;
  esac
  echo
  echo "== Removing cloned repository =="
  cd "$HOME"
  rm -rf -- "$REPO_DIR"
  echo "Removed $REPO_DIR"
fi

echo
echo "Uninstallation actions completed."
echo "Shared Termux packages and Android add-on apps were intentionally left installed."
echo "Review your remaining Termux packages manually; some may be used by other projects."
